def read_u16(table_rva, index):
    """uint16 read at table_rva + 2*index from the known initialized words.

    Tables are laid out contiguously in .data; an index past a table's end
    reads the next known table where addresses coincide, otherwise fails.
    """
    address = table_rva + 2 * index
    for base, values in list(AGE_TABLES.items()) + list(TEMPERATURE_TABLES.items()):
        if base <= address < base + 2 * len(values) and not (address - base) & 1:
            return values[(address - base) // 2] & 0xFFFF
    raise SchedulerGap(f'uint16 at RVA {address:#x} ({table_rva:#x}[{index}]) is not captured')
